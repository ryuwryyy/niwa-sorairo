const FERT_DEFAULT = (m) =>
  m <= 2 || m === 12 ? "寒肥。株のまわり(枝先の真下あたり)に浅い穴を掘り、油かすや有機肥料を埋める。"
    : m <= 4 ? "春の肥料。芽吹きに合わせて、ゆっくり効く肥料(緩効性)を株元にひとつかみ。"
    : m <= 8 ? "お礼肥。花や実で疲れた木に、化成肥料を少し。"
    : "秋の肥料。来年の花と実のために、株元に少量。";

/** その月の作業一覧を返す。[{ kind, text }] */
export function tasksFor(p, m) {
  const t = [];
  if (p.prune.includes(m)) t.push({ kind: "剪定", text: p.pruneHow });
  const ex = p.extra[m];
  if (ex) t.push({ kind: ex[0], text: ex[1] });
  if (p.harvest?.includes(m)) t.push({ kind: "収穫", text: p.harvestHow });
  if (p.fert.includes(m)) t.push({ kind: "肥料", text: p.fertHow[m] || FERT_DEFAULT(m) });
  if (p.pests.includes(m)) t.push({ kind: "虫", text: p.pest });
  if (p.dry && (m === 7 || m === 8) && ex?.[0] !== "水") t.push({ kind: "水", text: p.water });
  if (p.see[m]) t.push({ kind: "見頃", text: p.see[m] });
  return t;
}

/** 見頃以外に何か手を入れる作業があるか */
export const hasWork = (tasks) => tasks.some((t) => t.kind !== "見頃");

// — 名前判定の結果から植物を探す —
const toKata = (s) => String(s || "")
  .replace(/[ぁ-ゖ]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 0x60))
  .replace(/[ァィゥェォャュョッ]/g, (c) => ({ ァ: "ア", ィ: "イ", ゥ: "ウ", ェ: "エ", ォ: "オ", ャ: "ヤ", ュ: "ユ", ョ: "ヨ", ッ: "ツ" }[c]))
  .replace(/[\s・()()]/g, "");

export const normalizeName = toKata;

export function findPlant(...names) {
  const keys = names.map(toKata).filter(Boolean);
  return PLANTS.find((p) =>
    [p.name, p.kana, ...(p.alias || [])].map(toKata).some((k) => keys.includes(k)));
}

